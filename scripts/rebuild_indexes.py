#!/usr/bin/env python3
"""Build compact category retrieval indexes from existing Markdown files."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


CATEGORY_ROUTES: dict[str, list[tuple[str, str]]] = {
    "ctf-ai-ml": [("adversarial inputs, perturbations", "adversarial-ml.md"), ("model extraction or inversion", "model-attacks.md"), ("LLM, prompt, or LoRA attacks", "llm-attacks.md")],
    "ctf-crypto": [("RSA, modulus, signatures", "rsa-attacks.md"), ("AES, modes, MACs, oracles", "modern-ciphers.md"), ("LWE, HNP, short errors", "lattice-and-lwe.md"), ("PRNG or predictable state", "prng.md"), ("ECC or nonce reuse", "ecc-attacks.md")],
    "ctf-forensics": [("PCAP, protocol, timing", "network.md"), ("disk or memory image", "disk-and-memory.md"), ("image steganography", "stego-image.md"), ("audio or signal", "stego-advanced.md"), ("Windows artifacts", "windows.md")],
    "ctf-malware": [("obfuscated script or shellcode", "scripts-and-obfuscation.md"), ("C2 traffic or encrypted protocol", "c2-and-protocols.md"), ("PE, .NET, or config extraction", "pe-and-dotnet.md")],
    "ctf-misc": [("Python jail", "pyjails.md"), ("restricted shell", "bashjails.md"), ("encoding or QR", "encodings.md"), ("RF or SDR", "rf-sdr.md"), ("game, toy VM, or constraint", "games-and-vms.md")],
    "ctf-osint": [("social media or username", "social-media.md"), ("image geolocation or landmark", "geolocation-and-media.md"), ("DNS, archive, public web", "web-and-dns.md")],
    "ctf-pwn": [("stack overflow or ret2win", "overflow-basics.md"), ("ROP or shellcode", "rop-and-shellcode.md"), ("format string", "format-string.md"), ("heap allocator", "heap-techniques.md"), ("kernel target", "kernel.md")],
    "ctf-reverse": [("tool selection and static triage", "tools.md"), ("dynamic hooks or symbolic execution", "tools-dynamic.md"), ("anti-debug or anti-VM", "anti-analysis.md"), ("custom VM or transform", "patterns.md"), ("language or framework", "languages.md")],
    "ctf-web": [("SQL injection", "sql-injection.md"), ("SSTI, SSRF, LFI", "server-side.md"), ("upload or execution", "server-side-exec.md"), ("XSS, CSP, admin bot", "client-side.md"), ("JWT, OAuth, authz", "auth-and-access.md")],
}


def headings(path: Path, limit: int = 6) -> list[str]:
    found: list[str] = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"^#{2,4}\s+(.+?)\s*$", line)
        if match and not match.group(1).lower().startswith(("prerequisite", "additional resources", "quick start")):
            found.append(match.group(1).strip())
        if len(found) >= limit:
            break
    return found


def build_index(root: Path, category: str) -> str:
    directory = root / category
    lines = [
        f"# {category} Retrieval Index",
        "",
        "<!-- Generated by scripts/rebuild_indexes.py; do not hand-edit. -->",
        "Use this index after category selection. Open only the reference whose signal matches the current hypothesis.",
        "",
        "## High-signal routes",
        "",
        "| Evidence or symptom | Start with |",
        "|---|---|",
    ]
    for signal, filename in CATEGORY_ROUTES[category]:
        if (directory / filename).is_file():
            lines.append(f"| {signal} | [{filename}]({filename}) |")
    lines.extend(["", "## File catalog", ""])
    for path in sorted(directory.glob("*.md")):
        if path.name in {"INDEX.md", "SKILL.md"}:
            continue
        topics = headings(path)
        summary = "; ".join(topics) if topics else "Supporting category knowledge"
        lines.append(f"- [{path.name}]({path.name}) — {summary}")
    lines.extend([
        "",
        "## Cross-category pivots",
        "",
        "- Native artifact plus confirmed memory-corruption primitive: reverse first, then pwn.",
        "- Encrypted material recovered from packets or disk: forensics first, then crypto.",
        "- Custom cipher implemented inside a binary: reverse primary, crypto secondary.",
        "- Image hidden payload: forensics; image landmark identification: OSINT.",
        "- HTTP app whose core blocker is binary or crypto logic: keep web primary only while the HTTP trust boundary remains decisive.",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    stale: list[str] = []
    for category in CATEGORY_ROUTES:
        destination = root / category / "INDEX.md"
        content = build_index(root, category)
        if args.check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != content:
                stale.append(destination.relative_to(root).as_posix())
        else:
            destination.write_text(content, encoding="utf-8")
    if stale:
        print("stale indexes: " + ", ".join(stale))
        return 1
    print("category indexes are current" if args.check else f"rebuilt {len(CATEGORY_ROUTES)} category indexes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
